"""Can the battery-health estimate be checked against measured capacity? (ADR-0011)

    python -m edgecar.prep.evbattery --part 3          # once, in the training venv (torch reads the source files)
    python -m edgecar.bench.battery                    # writes eval/results/battery-validation.md and .json

EVBattery's engineers measured the capacity of some charging sessions. For each labelled session the estimator's
arithmetic — charge put in over state of charge gained — is applied to the session's snippets (summed, so their order
does not matter) and compared with the label: in absolute terms, and as tracking — whether the estimate falls where
the label falls, within one vehicle, as it ages.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from edgecar.analytics.battery import MIN_DSOC

SRC = Path("data/interim/evbattery")
OUT = Path("eval/results")
MIN_SESSIONS = 15  # per vehicle, for the tracking test


def sessions(snippets: pd.DataFrame, min_dsoc: float = MIN_DSOC) -> pd.DataFrame:
    lab = snippets[snippets["capacity"] > 0]
    g = lab.groupby(["car", "segment"]).agg(
        label=("capacity", "median"),
        ah=("ah", "sum"),
        dsoc=("dsoc", "sum"),
        snippets=("ah", "size"),
        mileage=("mileage", "median"),
    )
    g = g[g["dsoc"] >= min_dsoc].copy()
    g["estimate"] = g["ah"] / (g["dsoc"] / 100.0)
    g["ratio"] = g["estimate"] / g["label"]
    return g.reset_index()


def spearman(a: pd.Series, b: pd.Series) -> float:
    return float(a.rank().corr(b.rank()))


def tracking(s: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for car, g in s.groupby("car"):
        if len(g) < MIN_SESSIONS:
            continue
        rows.append(
            {
                "car": int(car),
                "sessions": len(g),
                "label_min": round(float(g["label"].min()), 2),
                "label_max": round(float(g["label"].max()), 2),
                "label_vs_mileage": round(spearman(g["label"], g["mileage"]), 2),
                "estimate_vs_label": round(spearman(g["estimate"], g["label"]), 2),
                "ratio_median": round(float(g["ratio"].median()), 3),
                "ratio_cv": round(float(g["ratio"].std() / g["ratio"].mean()), 3),
            }
        )
    return pd.DataFrame(rows)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--parts", nargs="+", type=int, default=[3])
    a = ap.parse_args()
    snippets = pd.concat(pd.read_csv(SRC / f"snippets{p}.csv") for p in a.parts)
    s = sessions(snippets)
    t = tracking(s)
    rho = float(t["estimate_vs_label"].median()) if len(t) else float("nan")
    res = {
        "source": "EVBattery (Tsinghua, CC BY 4.0), figshare 23301881, part(s) " + ", ".join(map(str, a.parts)),
        "snippets": int(len(snippets)),
        "labelled_sessions": int(len(s)),
        "vehicles": int(snippets["car"].nunique()),
        "ratio_estimate_to_label": {
            "median": round(float(s["ratio"].median()), 3),
            "p10": round(float(s["ratio"].quantile(0.1)), 3),
            "p90": round(float(s["ratio"].quantile(0.9)), 3),
        },
        "median_within_vehicle_rank_correlation": round(rho, 2),
        "verdict": "validates tracking" if rho >= 0.5 else "cannot validate",
        "per_vehicle": t.to_dict(orient="records"),
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "battery-validation.json").write_text(json.dumps(res, indent=2) + "\n", encoding="utf-8")
    r = res["ratio_estimate_to_label"]
    lines = [
        "# Battery health against measured capacity — what EVBattery can and cannot show",
        "",
        f"Generated by `python -m edgecar.bench.battery` from {res['source']}: {res['snippets']:,} charging snippets "
        f"from {res['vehicles']} vehicles; {res['labelled_sessions']} charging sessions with an engineer-measured "
        f"capacity gained at least {MIN_DSOC:.0f} % of charge (the rule the vehicle applies to drives). For each, "
        "EdgeCar's arithmetic — charge in ÷ state of charge gained — against the label.",
        "",
        f"**Absolute:** the estimate is {r['median']:.2f}× the label (10th–90th percentile {r['p10']:.2f}–"
        f'{r["p90"]:.2f}×). That is not an error of the method: to anonymise the data the authors "perturbed and '
        'interpolated the original average voltage, current, and temperature values" and "randomly shifted and '
        'scaled the timestamps" (arXiv:2201.12358, §3), so charge cannot be integrated in real units.',
        "",
        "**Tracking** — within one vehicle, does the estimate fall where the measured capacity falls? Spearman rank "
        "correlation across its sessions:",
        "",
        "| Vehicle | Sessions | Label range (Ah) | Label vs mileage | Estimate vs label | Estimate ÷ label (spread) |",
        "|---|---|---|---|---|---|",
    ]
    for row in res["per_vehicle"]:
        lines.append(
            f"| {row['car']} | {row['sessions']} | {row['label_min']:.1f}–{row['label_max']:.1f} | "
            f"{row['label_vs_mileage']:+.2f} | **{row['estimate_vs_label']:+.2f}** | {row['ratio_median']:.2f} · "
            f"±{100 * row['ratio_cv']:.0f} % |"
        )
    lines += [
        "",
        f"Median correlation **{rho:+.2f}**. The labels age as expected (they fall with mileage), but the estimate "
        "does not follow them: the labels move 3–8 % within a vehicle, while the session-to-session spread of the "
        "estimate on this anonymised data is about as large or larger. **This dataset cannot validate the estimate, "
        "for or against.**"
        if res["verdict"] == "cannot validate"
        else f"Median correlation **{rho:+.2f}**: the estimate tracks the measured capacity as the vehicles age.",
        "",
        "What follows for the passport: its interval is only the spread of one car's own measurements (on the i3, 23 "
        "drives within ±0.2 %), and the report says it is not yet validated against a laboratory capacity test. The "
        "next check is TU Munich's *Electric Vehicle Usage and State of Health Data* (mediaTUM 1845276, CC BY-SA "
        "4.0), which records real current and time with measured state of health.",
    ]
    (OUT / "battery-validation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
