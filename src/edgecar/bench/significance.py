"""How far the accuracy numbers can be trusted, and where the errors are.

    python -m edgecar.bench.significance                       # writes eval/results/significance.md

Reads the scored runs in ``eval/results/rerun`` (from ``edgecar.bench.nlu_eval``) and reports, for every model:

* accuracy with a 95 % Wilson interval — the sets are small, so one question is worth 1.4–2.5 points;
* paired exact McNemar tests against the stock few-shot model on the *same* questions;
* what kind of mistake each error is (wrong question type, wrong metric, wrong time window, a question declined
  that should have been answered, or the reverse), with the questions themselves.

Only blind sets are pooled (held-out 70 + refusal test 40). The dev sets were used to write the rules and to pick
the training epoch, so they are reported apart and never mixed into a headline.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

from edgecar.nlu import command
from edgecar.stats import mcnemar_exact, wilson

BASELINE = "qwen2.5-1.5b-fewshot"
MODELS = {  # file-name tag → label
    BASELINE: "Qwen2.5-1.5B, few-shot (stock)",
    "edgecar-0.5b-q4_k_m": "edgecar-0.5b Q4_K_M",
    "edgecar-0.5b-q8_0": "edgecar-0.5b Q8_0",
    "edgecar-1.5b-q4_k_m": "edgecar-1.5b Q4_K_M",
    "edgecar-1.5b-q8_0": "edgecar-1.5b Q8_0",
}
SETS = {  # file-name prefix → (label, blind?)
    "test-hybrid": ("Held-out 70, rules + model", True),
    "refusal_test-hybrid": ("Refusal test 40, rules + model", True),
    "test-slm": ("Held-out 70, model alone", True),
    "questions-hybrid": ("Dev 122, rules + model", False),
    "questions-slm": ("Dev 122, model alone", False),
    "refusal_dev-hybrid": ("Refusal dev 20, rules + model", False),
}
POOLED = ("test-hybrid", "refusal_test-hybrid")  # what the product does, on questions nobody tuned against


def load(results: Path, prefix: str, tag: str) -> dict[str, dict] | None:
    p = results / f"{prefix}-{tag}.json"
    if not p.exists():
        return None
    return {r["id"]: r for r in json.loads(p.read_text(encoding="utf-8"))["rows"]}


def kind_of_error(row: dict) -> str:
    """The closest accepted answer decides what went wrong."""
    try:
        pred = command.parse(row["pred"])
    except ValueError:
        return "invalid command"
    golds = [command.parse(g) for g in row["gold"]]
    if pred is None:
        return "declined an answerable question"
    if all(g is None for g in golds):
        return "answered what it should decline"
    fields = ("intent", "metric", "event", "compare_by", "direction", "window")

    def diff(g) -> list[str]:
        return [f for f in fields if getattr(g, f) != getattr(pred, f)]

    nearest = min((diff(g) for g in golds if g is not None), key=len)
    if "intent" in nearest:
        return "wrong question type"
    if nearest == ["window"]:
        return "wrong time window (read by code, not the model)"
    return "wrong " + "/".join(f.replace("compare_by", "comparison") for f in nearest if f != "window")


def pct(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} = **{k / n:.1%}** ({lo:.1%}–{hi:.1%})"


def report(results: Path) -> str:
    runs = {(s, m): load(results, s, m) for s in SETS for m in MODELS}
    out = [
        "# How far the accuracy numbers can be trusted",
        "",
        "Generated by `python -m edgecar.bench.significance` from the runs in `eval/results/rerun` (x86, 2 threads).",
        "Intervals are 95 % Wilson score intervals; p-values are two-sided exact McNemar tests on the same questions",
        f"against the stock model ({MODELS[BASELINE]}).",
        "",
        "## Accuracy",
        "",
        "| Set | " + " | ".join(MODELS.values()) + " |",
        "|---|" + "---|" * len(MODELS),
    ]
    for s, (label, blind) in SETS.items():
        cells = []
        for m in MODELS:
            rows = runs[s, m]
            cells.append(pct(sum(r["ok"] for r in rows.values()), len(rows)) if rows else "–")
        out.append(f"| {label}{'' if blind else ' *(dev: tuned on)*'} | " + " | ".join(cells) + " |")

    out += [
        "",
        "## Is any model better than the stock one?",
        "",
        "Blind questions only: the held-out set and the refusal test, pooled (110 questions), as the product runs",
        "them (rules first, then the model); and the held-out set with the model answering every question.",
        "",
        "| Model | Pooled blind (110) | wins · losses vs stock | p | Model alone (70) | wins · losses | p |",
        "|---|---|---|---|---|---|---|",
    ]
    base_pool = {i: r for s in POOLED for i, r in (runs[s, BASELINE] or {}).items()}
    base_slm = runs["test-slm", BASELINE] or {}
    for m, label in MODELS.items():
        if m == BASELINE:
            out.append(
                f"| {label} | {pct(sum(r['ok'] for r in base_pool.values()), len(base_pool))} | baseline | | "
                f"{pct(sum(r['ok'] for r in base_slm.values()), len(base_slm))} | baseline | |"
            )
            continue
        pool = {i: r for s in POOLED for i, r in (runs[s, m] or {}).items()}
        slm = runs["test-slm", m] or {}
        cells = [label]
        for mine, base in ((pool, base_pool), (slm, base_slm)):
            if not mine or mine.keys() != base.keys():
                cells += ["–", "–", "–"]
                continue
            wins = sum(mine[i]["ok"] and not base[i]["ok"] for i in mine)
            losses = sum(base[i]["ok"] and not mine[i]["ok"] for i in mine)
            cells += [pct(sum(r["ok"] for r in mine.values()), len(mine)), f"{wins} · {losses}"]
            cells.append(f"{mcnemar_exact(wins, losses):.2f}")
        out.append("| " + " | ".join(cells) + " |")
    out += [
        "",
        "With so few disagreements no difference on the blind sets is statistically significant: the fine-tuned",
        "models are *at least as accurate* as the stock one there, not proven better. What fine-tuning changed",
        "beyond doubt is the model alone on the dev questions (82.8 % → 99.2 %), speed and start-up — and a larger,",
        "outside-written test set ([`eval/outside/`](../outside/README.md)) is what can settle accuracy.",
        "",
        "## What kind of mistakes (blind sets, rules + model)",
        "",
    ]
    for m, label in MODELS.items():
        errors = [r for s in POOLED for r in (runs[s, m] or {}).values() if not r["ok"]]
        if not runs[POOLED[0], m]:
            continue
        kinds = Counter(kind_of_error(r) for r in errors)
        summary = ", ".join(f"{k} {v}" for k, v in kinds.most_common()) or "none"
        out.append(f"**{label}** — {len(errors)} errors: {summary}")
        out.append("")
        for r in errors:
            out.append(f"- `{r['path']}` {kind_of_error(r)}: “{r['q']}” → `{r['pred']}` (expected `{r['gold'][0]}`)")
        out.append("")
    shared = None
    for m in MODELS:
        if runs[POOLED[0], m]:
            wrong = {i for s in POOLED for i, r in runs[s, m].items() if not r["ok"]}
            shared = wrong if shared is None else shared & wrong
    if shared:
        out += [
            f"Missed by every model ({len(shared)}): " + ", ".join(sorted(shared)) + ". Errors every model shares sit",
            "in the deterministic parts (the rules, the time-phrase reader) or in a label, not in any one model. They",
            "are reported, not fixed: fixing code after reading a held-out question would quietly un-blind the set.",
            "",
        ]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", type=Path, default=Path("eval/results/rerun"))
    ap.add_argument("--out", type=Path, default=Path("eval/results/significance.md"))
    a = ap.parse_args()
    text = report(a.results)
    a.out.write_text(text + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
